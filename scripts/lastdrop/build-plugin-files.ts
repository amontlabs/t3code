/**
 * Embeds the vendored plugin folder (`packages/lastdrop-plugin/lastdrop/`) into a module the server bundles,
 * so a packaged app needs no resource beside it: the server writes the files under lastdrop's folder
 * (`installPlugin`). Run by `sync-plugin.sh`; `plugin.test.ts` fails while the module lags the folder.
 */
// @effect-diagnostics-next-line nodeBuiltinImport:off - A small build script over a folder.
import * as NodeFS from "node:fs";
// @effect-diagnostics-next-line nodeBuiltinImport:off - A small build script over a folder.
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const repoRoot = NodePath.resolve(
  NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)),
  "../..",
);
const folder = NodePath.join(repoRoot, "packages/lastdrop-plugin/lastdrop");
const output = NodePath.join(repoRoot, "packages/lastdrop-node/src/pluginFiles.generated.ts");

const files = (directory: string, prefix = ""): Array<string> =>
  NodeFS.readdirSync(directory, { withFileTypes: true })
    .toSorted((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) =>
      entry.isDirectory()
        ? files(NodePath.join(directory, entry.name), `${prefix}${entry.name}/`)
        : [`${prefix}${entry.name}`],
    );

const entries = files(folder).map(
  (path) =>
    `  ${JSON.stringify(path)}: ${JSON.stringify(NodeFS.readFileSync(NodePath.join(folder, path), "utf8"))},`,
);
NodeFS.writeFileSync(
  output,
  `// Generated by scripts/lastdrop/build-plugin-files.ts from packages/lastdrop-plugin/lastdrop. Do not edit.
export const PLUGIN_FILES: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`,
);
